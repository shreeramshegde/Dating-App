#!/usr/bin/env bash
set -e

# ==============================================================================
# Script: update-cors.sh
# Purpose: Dynamically update allowed CORS origins for Dating App Backend
# Usage:
#   ./scripts/update-cors.sh <frontend-ip-or-url>
# Examples:
#   ./scripts/update-cors.sh 54.210.12.34
#   ./scripts/update-cors.sh http://54.210.12.34:5173
#   ./scripts/update-cors.sh https://myfrontend.vercel.app
#   ./scripts/update-cors.sh  (interactive prompt)
# ==============================================================================

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${PROJECT_DIR}/.env.local"

# Fallback to .env if .env.local doesn't exist (e.g. on EC2 production instance)
if [ ! -f "${ENV_FILE}" ]; then
    if [ -f "${PROJECT_DIR}/.env" ]; then
        ENV_FILE="${PROJECT_DIR}/.env"
    elif [ -f "${PROJECT_DIR}/.env.example" ]; then
        cp "${PROJECT_DIR}/.env.example" "${ENV_FILE}"
        echo "Created ${ENV_FILE} from template .env.example"
    else
        touch "${ENV_FILE}"
    fi
fi

RAW_INPUT="$1"
if [ -z "$RAW_INPUT" ]; then
    echo "========================================================"
    echo " Dating App - Update CORS Allowed Origins"
    echo "========================================================"
    read -rp "Enter Frontend IP, Domain, or URL (e.g. 54.210.12.34 or https://myfrontend.vercel.app): " RAW_INPUT
fi

if [ -z "$RAW_INPUT" ]; then
    echo "Error: No frontend IP or URL provided. CORS origins unchanged."
    exit 1
fi

# Split by comma in case multiple entries were provided
IFS=',' read -ra ADDR_LIST <<< "$RAW_INPUT"
NEW_ORIGINS=()

for item in "${ADDR_LIST[@]}"; do
    item="$(echo "$item" | xargs)" # trim whitespace
    [ -z "$item" ] && continue

    # If already starts with http:// or https://
    if [[ "$item" =~ ^https?:// ]]; then
        NEW_ORIGINS+=("$item")
    else
        # If it's a raw IP or domain (e.g. 54.210.12.34 or 54.210.12.34:5173)
        if [[ "$item" == *:* ]]; then
            # Has specific port (e.g. 54.210.12.34:5173)
            NEW_ORIGINS+=("http://${item}")
            NEW_ORIGINS+=("https://${item}")
        else
            # IP or domain without port -> allow wildcard ports + standard ports
            NEW_ORIGINS+=("http://${item}:*")
            NEW_ORIGINS+=("https://${item}:*")
            NEW_ORIGINS+=("http://${item}")
            NEW_ORIGINS+=("https://${item}")
        fi
    fi
done

# Default local origins to preserve for developer convenience
DEFAULT_ORIGINS=(
    "http://localhost:5173"
    "http://localhost:3000"
    "http://127.0.0.1:5173"
    "http://127.0.0.1:3000"
)

# Merge default origins and new origins uniquely
ALL_ORIGINS=("${DEFAULT_ORIGINS[@]}")
for origin in "${NEW_ORIGINS[@]}"; do
    # Only add if not already in array
    if [[ ! " ${ALL_ORIGINS[*]} " =~ " ${origin} " ]]; then
        ALL_ORIGINS+=("$origin")
    fi
done

# Join with commas
CORS_VALUE=$(IFS=, ; echo "${ALL_ORIGINS[*]}")

echo "Updating CORS_ALLOWED_ORIGINS in ${ENV_FILE}..."

# If CORS_ALLOWED_ORIGINS already exists in file, replace it. Otherwise, append it.
if grep -q "^CORS_ALLOWED_ORIGINS=" "${ENV_FILE}"; then
    # Cross-platform sed replace
    sed -i.bak "s|^CORS_ALLOWED_ORIGINS=.*|CORS_ALLOWED_ORIGINS=${CORS_VALUE}|" "${ENV_FILE}" && rm -f "${ENV_FILE}.bak"
else
    echo "" >> "${ENV_FILE}"
    echo "# CORS Configuration (Auto-generated by update-cors.sh)" >> "${ENV_FILE}"
    echo "CORS_ALLOWED_ORIGINS=${CORS_VALUE}" >> "${ENV_FILE}"
fi

echo "Successfully configured CORS origins:"
for origin in "${ALL_ORIGINS[@]}"; do
    echo "  - ${origin}"
done

# Check if Docker compose is running and reload if so
if command -v docker >/dev/null 2>&1; then
    if docker ps --format '{{.Names}}' | grep -q "dating-backend"; then
        echo ""
        echo "Found running container 'dating-backend'. Reloading environment..."
        if [ -f "${PROJECT_DIR}/docker-compose.yml" ]; then
            (cd "${PROJECT_DIR}" && docker compose --env-file "${ENV_FILE}" up -d)
        else
            docker restart dating-backend
        fi
        echo "dating-backend container reloaded with new CORS configuration!"
    else
        echo ""
        echo "Note: Docker container 'dating-backend' is not currently running."
        echo "Start it with: docker compose --env-file ${ENV_FILE} up -d"
    fi
fi

echo ""
echo "Done! The backend will now accept cross-origin requests from the specified frontend."
